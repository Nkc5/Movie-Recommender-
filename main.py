import ast

def extract(arr):

  result = []
  counter = 0

  for obj in ast.literal_eval(arr):
    if counter < 3:
      result.append(obj['name'])
      counter+=1
    else:
      break

  return result

movies['cast'] = movies['cast'].apply(extract)
