# in crew only director name required

import ast

def get_director(arr):

  result = []

  for obj in ast.literal_eval(arr):

    if obj['job'] == 'Director':
      result.append(obj['name'])
      break

  return result

movies['crew'] = movies['crew'].apply(get_director)
