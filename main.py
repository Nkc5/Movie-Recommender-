# now check similarity between vectors (cosine similarity)

from sklearn.metrics.pairwise import cosine_similarity

similarity = cosine_similarity(vectors)

similarity

# now recommend 5 similar movies to user

def recommend(movie):

  # first we get index of movie
  matches = df[
        df['title'].str.strip().str.lower().str.contains(movie.strip().lower(), na=False, regex=False)
        ]

  if matches.empty:
      return []

  index = matches.index[0]
    
  # now get similarity vector
  distances = similarity[index]

  # now sort (high similarity first)
  movie_list = sorted(list(enumerate(distances)), reverse=True, key=lambda x : x[1])[1:6]

  # now return 5 movies
  recommendations = []

  for tup in movie_list:
      recommendations.append(df.iloc[tup[0]].title)
  
  return recommendations

