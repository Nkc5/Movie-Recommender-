import nltk
from nltk.stem.porter import PorterStemmer
ps = PorterStemmer()

# Stemming : convert word to its root

def stem(text):

  result = []

  for word in text.split():
    result.append(ps.stem(word))

  return " ".join(result)

stem("loving caring running clicked")

df['tags'] = df['tags'].apply(stem)
